def empty_title(has_tasks: bool, all_done: bool) -> str:
    """按状态取空状态主文案。

    ``has_tasks=False`` —— 一条任务都没有；
    ``has_tasks=True, all_done=True`` —— 有任务且今天全完成了。
    其余组合（有任务但没做完）不该走空状态，返回空串由调用方忽略。
    """
    if not has_tasks:
        return EMPTY_ALL_TITLE
    if all_done:
        return EMPTY_DONE_TITLE
    return ""


def empty_hint(has_tasks: bool, all_done: bool) -> str:
    """与 :func:`empty_title` 配套的副文案。"""
    if not has_tasks:
        return EMPTY_ALL_HINT
    if all_done:
        return EMPTY_DONE_HINT
    return ""


def encourage(today_count: int) -> str:
    """摘要卡里那句话。

    ``today_count == 0`` 必须回落到 :data:`EMPTY_ALL_TITLE` —— 这正是需求 ④
    要修的地方：上一版这里写的是"今天还没有拾起任何光，**添加第一个任务吧**"，
    而空状态卡片写的是"今天还没有拾起任何光"，同一屏里两句话长得像又不一样，
    看着像刷新没刷干净。现在两者**同源**，改一处两处都变。
    """
    if today_count <= 0:
        return EMPTY_ALL_TITLE
    for threshold, template in _ENCOURAGE_TABLE:
        if today_count >= threshold:
            return template.format(n=today_count)
    return EMPTY_ALL_TITLE


